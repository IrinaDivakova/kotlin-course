//Задача 24. Характеристика числовой коллекции
//Напиши функцию, которая принимает коллекцию чисел и возвращает строку с характеристикой коллекции используя конструкцию when
//
//Если коллекция пустая - “Пусто”
//Если количество элементов меньше пяти - “Короткая”
//Если коллекция начинается с 0 - “Стартовая”
//Если сумма всех чисел больше 10000 - “Массивная”
//Если среднее значение равно 10 - “Сбалансированная”
//Если длина строки образованная склеиванием коллекции в строку равна 20 - “Клейкая”
//Если максимальное число меньше -10 - “Отрицательная”
//Если минимальное число больше 1000 - “Положительная”
//Если содержит одновременно числа 3 и 14 - “Пи***тая”
//Иначе - “Уникальная”
//Вызвать метод с данными, подходящими под каждую из веток
//
fun numberCollectionCharacteristic(a: List<Int>): String {
    return when {
        a.isEmpty() -> "Пусто"
        a.size < 5 -> "Короткая" //Если количество элементов меньше пяти - “Короткая”
        a.first() == 0 -> "Стартовая" //Если коллекция начинается с 0 - “Стартовая”
        a.sum() > 10000 -> "Массивная"//Если сумма всех чисел больше 10000 - “Массивная”
        a.average() == 10.0 -> "Сбалансированная" //Если среднее значение равно 10 - “Сбалансированная”
        a
            .joinToString()
            .length == 20 -> "Клейкая" //Если длина строки образованная склеиванием коллекции в строку равна 20 - “Клейкая”
        a.max() < -10 -> "Отрицательная" //Если максимальное число меньше -10 - “Отрицательная”
        a.min() > 1000 -> "Положительная" //Если минимальное число больше 1000 - “Положительная”
        a.contains(3) && a.contains(14) -> "Пи***тая" //Если содержит одновременно числа 3 и 14 - “Пи***тая”
        else -> "Уникальная"//Иначе - “Уникальная”
    }
}

//Задача 25. Анализ учебных оценок
//Напиши функцию, которая принимает список чисел и возвращает список чисел.
fun gradesAnalizer(list: List<Int>): List<Int> {
    return list
        .filter { it >= 60 }
        .sorted()
        .take(3)
}

